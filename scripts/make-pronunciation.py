#!/usr/bin/env python3
"""make-pronunciation.py <lang> [--out PATH] — regenerate a pronunciation bridge from the phrase bank.

    A learner who cannot read the script cannot say what we serve. This script generates
    data/pronunciation-<lang>.json by reading the engine's own bank, so the reading can never
    drift from the phrases actually served.

WHY A SCRIPT AND NOT A ONE-OFF COMMAND: the first version of this file was built by an ad-hoc
shell command that no longer exists. A generated artifact with no generator is a dead end — the
next phrase added to the bank would have had no reading and no way to get one.

REQUIREMENTS (the host has no pip; use uv):
    uv venv <dir> --python 3.13
    VIRTUAL_ENV=<dir> uv pip install pythainlp
    <dir>/bin/python make-pronunciation.py th

CONTRACT — adding a language is adding a branch here plus a bank, never editing the callers:
    the output is always {"_what", "_tool", "_LIMIT_*", "dialect", "phrases": {phrase: reading},
    "female_derived_from": {female_phrase: male_phrase}}.

HONEST LIMIT, carried into the file itself: the thai branch produces NO TONE MARKS. RTGS drops
them and thai2rom_onnx returns the same string, measured 2026-10-17. Thai tones are lexical, so
this is a bridge to being UNDERSTOOD, not to being RIGHT. Do not let a downstream reader assume
tones are handled.
"""
import argparse
import importlib.machinery
import importlib.util
import json
import pathlib
import sys

SKILL_DIR = pathlib.Path(__file__).resolve().parents[1]      # <seat>/skills/edu
DATA = SKILL_DIR / "data"
ENGINE = pathlib.Path(__file__).resolve().parent / "life-lesson-engine.py"

# Female-form derivation per language: (male_markers, female_markers). Thai polite particles and the
# first-person pronoun are gendered, so a bank written in one form must be bridged for the other.
FEMALE_MAP = {"th": [("ครับ", "ค่ะ"), ("ผม", "ฉัน")]}


def load_engine():
    """Import the engine by path — its filename has hyphens, so importlib needs a loader."""
    loader = importlib.machinery.SourceFileLoader("lle", str(ENGINE))
    spec = importlib.util.spec_from_loader("lle", loader)
    mod = importlib.util.module_from_spec(spec)
    # Suppress the engine's import-time stderr chatter about trip data; this script only reads banks.
    loader.exec_module(mod)
    return mod


def romanizer(lang: str):
    if lang != "th":
        raise SystemExit(f"🔴 make-pronunciation: no romanizer for '{lang}'. Adding one is a branch "
                         f"here — do NOT invent readings by hand.")
    try:
        from pythainlp.tokenize import word_tokenize
        from pythainlp.transliterate import romanize
        import pythainlp
    except ImportError as e:
        raise SystemExit(f"🔴 pythainlp not importable ({e}). Install it in a uv venv — see this "
                         f"file's docstring. Do not hand-write readings.")
    version = pythainlp.__version__

    def rom(text: str) -> str:
        # Tokenize FIRST. Romanizing a phrase whole mashes it (ผมมาเที่ยวครับ -> phommathiaokhrap).
        toks = word_tokenize(text, engine="newmm", keep_whitespace=False)
        return " ".join(romanize(t, engine="royin") for t in toks)

    return rom, version


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("lang", help="language code, e.g. th")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()

    engine = load_engine()
    dialect = next((d for d in engine.PHRASES if d.startswith(a.lang + "-")), None)
    if not dialect:
        raise SystemExit(f"🔴 no bank for language '{a.lang}' in the engine — add the pack first "
                         f"(adding a subject is adding a file).")
    rom, version = romanizer(a.lang)

    phrases, female_from = {}, {}
    for _situation, rows in engine.PHRASES[dialect].items():
        for row in rows:
            th = row[0]
            phrases[th] = rom(th)
            female = th
            for m, f in FEMALE_MAP.get(a.lang, []):
                female = female.replace(m, f)
            if female != th:
                phrases[female] = rom(female)          # keyed AFTER the swap, which is when it is read
                female_from[female] = th

    doc = {
        "_what": "PRONUNCIATION BRIDGE — PACK DATA. Latin reading for each bank phrase, keyed by the "
                 "EXACT phrase the engine renders (both learner forms present, so the lookup survives "
                 "the form swap).",
        "_tool": f"PyThaiNLP {version} — word_tokenize(engine='newmm') then "
                 f"transliterate.romanize(engine='royin', Royal Thai General System). GENERATED by "
                 f"scripts/make-pronunciation.py, never hand-typed.",
        "_why_tokenize": "Romanizing whole phrases mashes them; tokenizing first reads them.",
        "_LIMIT_NO_TONES": "NO TONE MARKS — measured 2026-10-17: RTGS drops them and thai2rom_onnx "
                           "returns the same string. Thai tones are lexical, so this gets a learner "
                           "UNDERSTOOD, not RIGHT. Tone-marked readings need a curated dataset.",
        "_count": len(phrases),
        "dialect": dialect,
        "phrases": dict(sorted(phrases.items())),
        "female_derived_from": female_from,
    }
    out = pathlib.Path(a.out) if a.out else DATA / f"pronunciation-{a.lang}.json"
    out.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n")
    print(f"✅ {out} — {len(phrases)} readings ({len(female_from)} female-derived), "
          f"bank={dialect}, tool=PyThaiNLP {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
